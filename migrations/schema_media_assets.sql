-- D1 Schema for Archival Figures, Photos, and Media Assets
CREATE TABLE IF NOT EXISTS media_assets (
  id TEXT PRIMARY KEY,             -- SHA256 or truncated unique hash of image
  doc_id TEXT NOT NULL,            -- Associated archive_documents(id) or PDF sha256
  doc_title TEXT,                  -- Human-readable document title
  page_number INTEGER,             -- 1-indexed page number in the source PDF
  bounding_box TEXT,               -- JSON array [x0, y0, x1, y1] on PDF page coordinates
  image_url TEXT NOT NULL,         -- Path/URL to asset (e.g., /api/assets/figures/<id>.webp)
  caption TEXT,                    -- Scholarly caption generated by multimodal vision AI
  category TEXT,                   -- diagram | histology | photo | chart | clipping | artwork | document
  keywords TEXT,                   -- JSON array of keywords
  is_sensitive INTEGER DEFAULT 0,  -- 0 = safe, 1 = sensitive (requires click-to-reveal)
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_media_doc_id ON media_assets(doc_id);
CREATE INDEX IF NOT EXISTS idx_media_category ON media_assets(category);
