import json

with open('public/api_entities_mock.json', 'r', encoding='utf-8') as f:
    existing = json.load(f)

with open('scratch/new_manifesto_entities.json', 'r', encoding='utf-8') as f:
    new_entries = json.load(f)

existing_ids = {e.get('id') for e in existing}
existing_names = {e.get('name', '').lower() for e in existing}

added = 0
for ne in new_entries:
    if ne['id'] not in existing_ids and ne['name'].lower() not in existing_names:
        existing.append(ne)
        existing_ids.add(ne['id'])
        existing_names.add(ne['name'].lower())
        added += 1

print(f"Added {added} new entities to mock dataset. Total entities now: {len(existing)}")

with open('public/api_entities_mock.json', 'w', encoding='utf-8') as f:
    json.dump(existing, f, indent=2, ensure_ascii=False)

# Generate updated D1 SQL migration
sql_lines = [
    "-- SQL Migration: Populate manifesto entities and full profiles in Cloudflare D1",
    "-- Generated by CircumSurvey Autonomous System",
    ""
]

for e in existing:
    eid = e.get('id', '')
    name = (e.get('name', '') or '').replace("'", "''")
    etype = (e.get('type', 'person') or '').replace("'", "''")
    desc = (e.get('description', '') or '').replace("'", "''")
    tagline = (e.get('tagline', '') or '').replace("'", "''")
    role = (e.get('role', '') or '').replace("'", "''")
    affiliations = (e.get('affiliations', '') or '').replace("'", "''")
    core_focus = (e.get('core_focus', '') or '').replace("'", "''")
    key_milestones = (e.get('key_milestones', '') or '').replace("'", "''")
    years_active = (e.get('years_active', '') or '').replace("'", "''")
    rating_score = e.get('rating_score', 3.0) or 3.0
    rating_grade = (e.get('rating_grade', 'C') or 'C').replace("'", "''")
    rating_quote = (e.get('rating_quote', '') or '').replace("'", "''")
    featured = 1 if e.get('featured') else 0
    slug = (e.get('slug', '') or '').replace("'", "''")

    sql = f"""INSERT INTO entities (id, type, name, description, tagline, role, featured, rating_score, rating_grade, rating_quote, years_active, affiliations, core_focus, key_milestones)
VALUES ('{eid}', '{etype}', '{name}', '{desc}', '{tagline}', '{role}', {featured}, {rating_score}, '{rating_grade}', '{rating_quote}', '{years_active}', '{affiliations}', '{core_focus}', '{key_milestones}')
ON CONFLICT(id) DO UPDATE SET
  name=excluded.name,
  description=excluded.description,
  tagline=excluded.tagline,
  role=excluded.role,
  featured=excluded.featured,
  rating_score=excluded.rating_score,
  rating_grade=excluded.rating_grade,
  rating_quote=excluded.rating_quote,
  years_active=excluded.years_active,
  affiliations=excluded.affiliations,
  core_focus=excluded.core_focus,
  key_milestones=excluded.key_milestones;"""
    sql_lines.append(sql)

with open('scripts/add_manifest_entities_d1.sql', 'w', encoding='utf-8') as f:
    f.write('\n'.join(sql_lines) + '\n')

print(f"Generated D1 SQL migration script: scripts/add_manifest_entities_d1.sql ({len(sql_lines)} statements)")
